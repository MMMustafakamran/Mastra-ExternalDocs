#!/usr/bin/env node
/**
 * Regenerate the README's status table (§8) from the two files that already
 * know the answer.
 *
 *   frontend/src/lib/nav-config.ts       every doc page, its route, its status
 *   autorecorder/config/pages.config.ts  which routes the recorder drives
 *
 * The table used to be typed by hand and disagreed with both: it said "three
 * agent ids" after a fourth was added, "all 17" after the recorder reached 20,
 * and carried a version the header had already moved past. nav-config.ts's
 * own comment claims the README reads from it; until this script, nothing did.
 *
 * The Notes column stays hand-written. It is parsed out of the existing table
 * by route and put back, so editing a note in the README is still the way to
 * change it; a route that gains a row for the first time gets its
 * `statusNote` from nav-config as a starting point.
 *
 *   node ci/write-readme-status.mjs          rewrite README.md in place
 *   node ci/write-readme-status.mjs --check  exit 1 if README.md is stale
 *
 * Both configs are read textually, like ci/lib/pages.mjs does, so this stays a
 * dependency-free .mjs and never imports Next.js code.
 */
import fs from 'node:fs';
import path from 'node:path';
import { FRONTEND_DIR, RECORDER_DIR, ROOT_DIR } from './lib/config.mjs';

const NAV_CONFIG = path.join(FRONTEND_DIR, 'src', 'lib', 'nav-config.ts');
const PAGES_CONFIG = path.join(RECORDER_DIR, 'config', 'pages.config.ts');
const README = path.join(ROOT_DIR, 'README.md');

const BEGIN = '<!-- status-table:begin — generated by ci/write-readme-status.mjs; edit Notes here, everything else in nav-config.ts -->';
const END = '<!-- status-table:end -->';

/** Nav groups that are harness chrome, not doc pages under test. */
const SKIP_GROUPS = new Set(['Doc Sync']);

const STATUS = {
  working: '✅ Working',
  partial: '⚠️ Partial',
  reference: '📖 Reference',
  broken: '❌ Broken',
  'not-started': '🚧 Not started',
};

function field(block, name) {
  // Values are single double-quoted string literals, possibly on the next line.
  const m = block.match(new RegExp(`\\b${name}:\\s*"((?:[^"\\\\]|\\\\.)*)"`));
  return m ? m[1] : undefined;
}

export function readNavRoutes() {
  const src = fs.readFileSync(NAV_CONFIG, 'utf8');
  const routes = [];

  // Groups open with `title: "...",\n    routes: [`; each route object is
  // indented six spaces and closes with a six-space `}`.
  const groupRe = /title:\s*"([^"]+)",\s*routes:\s*\[/g;
  const groups = [...src.matchAll(groupRe)].map((m) => ({ title: m[1], at: m.index }));

  // CRLF-tolerant: the checkout may carry either line ending.
  const routeRe = /\r?\n {6}\{\r?\n([\s\S]*?)\r?\n {6}\}/g;
  for (const m of src.matchAll(routeRe)) {
    const block = m[1];
    const group = [...groups].reverse().find((g) => g.at < m.index)?.title ?? '';
    const p = field(block, 'path');
    if (!p) continue;
    routes.push({
      group,
      path: p,
      docPath: field(block, 'docPath'),
      status: field(block, 'status'),
      statusNote: field(block, 'statusNote'),
      hasDemo: /\bhasDemo:\s*true/.test(block),
      offNav: /\boffNav:\s*true/.test(block),
    });
  }
  if (routes.length === 0) throw new Error(`No routes parsed from ${NAV_CONFIG}`);
  return routes;
}

export function readRecordedRoutes() {
  const src = fs.readFileSync(PAGES_CONFIG, 'utf8');
  return new Set([...src.matchAll(/^\s*route:\s*'([^']*)'/gm)].map((m) => `/${m[1]}`.replace(/\/+$/, '') || '/'));
}

/** Route → hand-written note, from whatever table README.md holds now. */
function existingNotes(readme) {
  const notes = new Map();
  for (const line of readme.split('\n')) {
    const cells = line.split('|').map((c) => c.trim());
    // | Doc page | Route | Status | (Recorded |) Notes |
    if (cells.length < 5 || !cells[2].startsWith('`')) continue;
    const route = cells[2].replace(/`/g, '');
    const note = cells[cells.length - 2];
    if (route.startsWith('/') && note !== 'Notes' && !/^-+$/.test(note)) notes.set(route, note);
  }
  return notes;
}

function pad(s, n) {
  return s + ' '.repeat(Math.max(0, n - [...s].length));
}

export function renderTable(routes, recorded, notes) {
  const rows = routes
    .filter((r) => !SKIP_GROUPS.has(r.group))
    .map((r) => {
      const note = notes.get(r.path) ?? r.statusNote ?? '';
      const rec = recorded.has(r.path) ? '🎬' : r.hasDemo ? '⚠️ demo, not recorded' : '—';
      return [`\`${r.docPath}\``, `\`${r.path}\``, STATUS[r.status] ?? r.status, rec, note];
    });

  const head = ['Doc page', 'Route', 'Status', 'Recorded', 'Notes'];
  const widths = head.map((h, i) => Math.max([...h].length, ...rows.map((r) => [...r[i]].length)));
  const line = (cells) => `| ${cells.map((c, i) => pad(c, widths[i])).join(' | ')} |`;
  return [line(head), line(widths.map((w) => '-'.repeat(w))), ...rows.map(line)].join('\n');
}

function splice(readme, table) {
  const b = readme.indexOf(BEGIN);
  const e = readme.indexOf(END);
  if (b !== -1 && e !== -1) {
    return readme.slice(0, b) + `${BEGIN}\n${table}\n${END}` + readme.slice(e + END.length);
  }
  // First run: claim the hand-written table, header row through last data row.
  const start = readme.indexOf('| Doc page');
  if (start === -1) throw new Error('README.md has neither markers nor a "| Doc page" table.');
  // The table ends at the first line that is not a table row.
  const tail = readme.slice(start).match(/\r?\n(?!\|)/);
  const stop = tail ? start + tail.index : readme.length;
  return readme.slice(0, start) + `${BEGIN}\n${table}\n${END}` + readme.slice(stop);
}

const check = process.argv.includes('--check');
const readme = fs.readFileSync(README, 'utf8');
const routes = readNavRoutes();
const recorded = readRecordedRoutes();
const next = splice(readme, renderTable(routes, recorded, existingNotes(readme)));

const unrecordedDemos = routes.filter((r) => r.hasDemo && !recorded.has(r.path)).map((r) => r.path);
if (unrecordedDemos.length > 0) {
  console.warn(`⚠️ Routes with a demo the recorder never drives: ${unrecordedDemos.join(', ')}`);
}

if (next === readme) {
  console.log('✅ README status table is current.');
} else if (check) {
  console.error('❌ README status table is stale. Run: node ci/write-readme-status.mjs');
  process.exit(1);
} else {
  fs.writeFileSync(README, next, 'utf8');
  console.log(`✏️  README status table rewritten (${routes.length} routes, ${recorded.size} recorded).`);
}
